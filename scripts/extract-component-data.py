#!/usr/bin/env python3
"""Copy the per-component data out of component-analysis.html into component-data.js.

The main portal (index.html) shows every component under the Vontron vendor and loads
component-data.js only when someone picks a component other than RO Membrane.
component-analysis.html stays the source: re-run this after its data is rebuilt.

    python3 scripts/extract-component-data.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
src = (ROOT / 'component-analysis.html').read_text(encoding='utf-8')


def grab(name):
    m = re.search(r'^\s*var ' + name + r' = (\{.*\});\s*$', src, re.M)
    if not m:
        raise SystemExit('component-analysis.html has no "var %s = {...};" line' % name)
    return json.loads(m.group(1))


data = grab('COMPONENT_DATA')
labels = grab('COMPONENT_LABELS')
out = ROOT / 'component-data.js'
out.write_text(
    '// Generated by scripts/extract-component-data.py from component-analysis.html. Do not edit.\n'
    'window.MW_COMPONENTS = ' + json.dumps({'data': data, 'labels': labels}, ensure_ascii=False, separators=(',', ':')) + ';\n',
    encoding='utf-8')
print('%s: %d components, %.1f MB' % (out.name, len(data), out.stat().st_size / 1e6))
